#!/usr/bin/env python3
"""Index retained REA evidence and export readable decompiler references.

The generated .c.txt files are analysis references, NOT buildable recovered C.
Raw provider output and evidence IDs are retained alongside them.
"""
from pathlib import Path
import csv
import json
import re


ROOT = Path(__file__).resolve().parents[1]


def structured(path):
    obj = json.loads(path.read_text())
    if obj.get('structuredContent'):
        return obj['structuredContent']
    for item in obj.get('content', []):
        if item.get('type') == 'text':
            try:
                return json.loads(item['text'])
            except ValueError:
                pass
    return obj


def main():
    directory = ROOT/'analysis/rea'
    destination = ROOT/'analysis/decompiler_reference'
    destination.mkdir(exist_ok=True)
    procedures = structured(directory/'original_procedures.json')['normalized_result']
    modules, rows = {}, []
    for procedure in procedures:
        address = procedure['address']
        linear = int(address, 16)
        image_offset = linear-0x10000
        file_offset = linear-0xF000
        name = procedure['value']
        match = re.search(r'FUN_([0-9a-f]+)_([0-9a-f]+)', name)
        module = match.group(1) if match else 'entry'
        path = directory/'pseudo_original'/f'{address}.json'
        row = dict(rea_address=address, image_offset=f'0x{image_offset:x}',
                   file_offset=f'0x{file_offset:x}', observed_name=name,
                   status='not_requested', evidence_id='', reference_file='')
        if path.exists():
            value = structured(path)
            pseudo = value.get('normalized_result')
            row['evidence_id'] = value.get('evidence_id', '')
            if isinstance(pseudo, str):
                row['status'] = 'decompiled_reference'
                row['reference_file'] = f'analysis/decompiler_reference/segment_{module}.c.txt'
                prefix = (f'\n/* {name}: REA {address}; image {row["image_offset"]}; '
                          f'file {row["file_offset"]}\n'
                          f' * Evidence: {row["evidence_id"]}\n */\n')
                modules.setdefault(module, []).append(prefix+pseudo)
            else:
                row['status'] = 'provider_error' if 'error' in value else 'no_pseudocode'
                row['error'] = value.get('error', value)
        rows.append(row)
    disclaimer = '''/* DECOMPILER REFERENCE ONLY -- NOT BUILDABLE RECOVERED C.
 * Generated by REA 6.7.0 / Ghidra 12.1.4 from the supplied SNAKE.EXE.
 * Names, types and boundaries may be incorrect. Real-mode segmentation,
 * hardware side effects and self-modifying code require separate analysis.
 * Buildable reconstructed implementations are in ../../src/.
 * This output does not establish original source text or binary matching.
 */\n'''
    for module, sections in modules.items():
        (destination/f'segment_{module}.c.txt').write_text(disclaimer+''.join(sections))
    with (ROOT/'analysis/procedure_inventory.csv').open('w', newline='') as fp:
        fields = ['rea_address','image_offset','file_offset','observed_name',
                  'status','evidence_id','reference_file']
        writer = csv.DictWriter(fp, fieldnames=fields, extrasaction='ignore')
        writer.writeheader(); writer.writerows(rows)
    counts = {status:sum(row['status']==status for row in rows)
              for status in sorted({row['status'] for row in rows})}
    summary = dict(total_observed_procedures=len(rows), counts=counts,
                   failed=[row for row in rows if row['status']=='provider_error'],
                   not_requested=[row for row in rows if row['status']=='not_requested'],
                   limitation='Pseudocode coverage is not C reconstruction coverage. '
                              'This inventory includes runtime library functions and '
                              'does not enumerate the decrypted graphics driver.')
    (ROOT/'analysis/rea_summary.json').write_text(json.dumps(summary, indent=2)+'\n')
    print(json.dumps(dict(total=len(rows), counts=counts, reference_modules=len(modules))))


if __name__ == '__main__':
    main()
